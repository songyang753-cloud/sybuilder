def section(s, title_pat):
    """取某一节的正文（到下一个同级标题为止）。

    ⚠️ 2026-09-04 全链实跑发现：本函数**只认标题**，
    而官方模板 `templates/definition-final.md` 把「不服务谁」写成
    **目标用户表里的一行**（`| ⭐ **不服务谁** | … |`）——
    于是**照着官方模板填的人必然被这道门判红**，
    而报错说的是「整节缺失」，**内容明明就在那里**。
    ⭐⭐ 这比误判本身更糟：一句错误的诊断会让人去找一个不存在的问题。
    ⭐ 修法要通用 —— 五个键（不服务谁/明确不做/单向门/失败路径/候选）
      在模板里有的是标题、有的是表行，判据必须两种都认。
    """
    # 🚨🚨 2026-09-10：这里**曾经是本仓的第二个 section 解析器** ——
    #   `^(#{1,3})\s*…` 手写一遍标题匹配，于是 `_section` 上修过的每一条
    #   （缩进 0–3 / `#` 后必须有空白 / setext / 代码围栏 / 空标题不崩 / 同名节）
    #   **在这里一条都没有**。而这道门是被构造空间穷举覆盖最多的一道 ——
    #   ⭐ 穷举扫的是 `answer_state`，扫不到它上游这个自己手写的取节器。
    #   ⇒ 委托给唯一正本。⛔ 一个仓里不许有两个 section 解析器。
    _sec = section_at(s, title_pat, regex=True)
    if _sec is not None:
        return _sec
    # 退回：找一张表里**首列命名了它**的那一行，取其余单元格当正文
    for ln in s.splitlines():
        ln = ln.strip()
        if not ln.startswith('|'):
            continue
        cells = [c.strip() for c in ln.strip('|').split('|')]
        if len(cells) < 2:
            continue
        head = re.sub(r'[`*⭐\s]', '', cells[0])
        if re.search(title_pat, head):
            return ' '.join(cells[1:])
    return None


# 🚨 2026-09-09 第二轮独立复核揪出：上一批只把「延后语」判据接进了**表列**那一条路径，
#   而 `_answered` 接受三种形态（成节 / 成表行 / 成表列）—— 表行与标题两种**照样绕过**，
#   且表行正是 `section()` 自己的 docstring 称为「官方模板惯用」的那种。
#   实证：一份只有标题+一张 18 行表、每格都写「以后再定，等上线后看数据」的文档，
#   报「✅ 18 项齐备」。⭐ **修一条路径不叫修好，三条路径必须共用同一判据。**
#   ⚠️ 前缀锚定（`^待|^以后…`）会误伤合法值（「暂估 2 人月」「待摊 3 人月」被判成延后）——
#   所以要求的是「**整段除了延后语再没有别的实质内容**」，而不是「开头像延后语」。
#   ⚠️ 2026-09-09 第三轮复核揪出**第五条绕过**：判据原来限制延后语的**尾巴长度**
#   （`[^。\n]{0,12}`）—— 于是「以后再定，等上线后看数据和用户反馈再确认。」
#   （尾巴 16 字）直接逃逸。⭐ **多写 4 个字就绕过，说明修的是那一发反例不是形状。**
#   ⇒ 换判据方向：不限长度，改判**整段有没有实质承诺**——
#     以延后语开头、且余下部分**不含任何具体承诺信号**（数字/阈值/日期/人名/
#     具体做法动词）的，一律算「还没答」。长度多少都不影响。
#   ⚠️ 自攻补漏（2026-09-09）：首版按**完整词**枚举，于是「待评估中」「暂时不做」
#     这类同义变体一步之内就逃逸。⇒ 改**词干 + 通配尾巴**（待X / 暂X / 以后X / 后续X…），
#     覆盖同一语义的自然变体，而不是继续往词表里加词。
# 延后语义词 —— ⚠️ 它**不再是判据本身**（判据见 is_defer 的「倒过来判」），
#   只用于「把延后措辞剔掉之后还剩多少实质内容」这一步。
#   所以这张表**不需要穷举**：漏掉几个词只会让剩余长度略大，
#   而真正的答案照样得靠 COMMIT_SIGNAL 或足够长的具体陈述才过。
DEFER_ANY = re.compile(
    r'待定|待补|待填|待议|待评估|待确认|暂定|暂缺|'
    r'以后再定|以后再说|以后补|后续补充|后续再定|回头再说|回头补|'
    # ⚠️ `不确定` 不加边界会咬进**不确定性**（「不确定性由风控模块兜底」是答案）。
    r'还没定|还没想|还未定|尚未确定|未定|不确定(?!性)|没想好|定不下来|'
    # 🚨 2026-09-10 第六轮：这张表里**混了两类词**，而它们的正确量程不同 ——
    #   ①**到处都是延后**（待定 / 以后再定 / 尚未确定）⇒ 子串匹配是对的；
    #   ②**只有独占整格时才是延后**（先不做 / 暂无 / 等数据 / 暂时）⇒ 子串匹配会
    #     咬进「先不做 X，**只做 Y**」「该字段暂无默认值，**由调用方必填**」
    #     「暂时**性**错误自动重试」——那些都是答案，不是延后。
    #   ⭐ 第②类已移交 `_PLACEHOLDER_ONLY`（整格匹配）与「剥完为空」两条路径，
    #     从本表删除。⛔ 删它们不是放宽：「先不做」独占一格时仍由残余为空判 NO。
    r'视情况而定|另行通知|延后处理|再说|再定|'
    # 🚨 2026-09-09 第五轮：`N/?A` 带 re.I 且**没有词边界** —— 它匹配任意英文里的
    #   「na」，官方正例里的 **Professional** 当场被判成「还没答」（`Professio[na]l`）。
    #   子代理在 research-gate 的 `_TRI` 上报了**同一个缺陷**：同一形状，两个文件各犯一次。
    #   ⇒ 英文词一律加词边界。
    # 🚨 裸字 `无` 同理：它会吃掉「无障碍支持」「无需登录」这类**合法答案**。
    #   单独一个「无」已由 _PLACEHOLDER_ONLY 收，这里删掉，免得误伤。
    r'TBD|to\s*be\s*determined|not\s*yet|(?<![A-Za-z])N/?A(?![A-Za-z])|'
    r'(?<![A-Za-z])pending(?![A-Za-z])|(?<![A-Za-z])later(?![A-Za-z])', re.I)
# 具体承诺信号 —— ⚠️ 2026-09-09 自攻修正：**「有数字」不能当承诺的代理指标**。
#   「以后再定，见 2026 年规划」里的数字是**指向别处**的，不是本项的答案，
#   而首版因为一个 `\d` 就判它「已回答」⇒ 一步编辑距离即绕过。
#   ⇒ 数字必须落在**量化语境**里（阈值/比例/时长/规模）才算承诺；
#     光有年份、编号、引用位置不算。
#   ⚠️ 2026-09-09 四轮复核：「采用/使用/保证」当承诺代理指标会**反向命中** ——
#     「待定，采用什么方案还没想好」因为一个「采用」就被判成已回答。
#     ⇒ 动作词必须带**宾语**（采用 X / 限制在 X），且该句不落在延后语义里。
COMMIT_SIGNAL = re.compile(
    # ⚠️ 「次/个/条」这类量词**前面带序数词时不是承诺**（「第 3 次评审」是在说
    #   什么时候再谈，不是给出阈值）⇒ 序数用法排除。
    # 🚨 2026-09-10：`(?<!第)` **遇到空格就失效** —— 「第 3 次」里 `3` 前面是空格，
    #   回顾断言看不到那个「第」⇒ 序数被当成承诺。自证当场抓到（既有缺陷，
    #   本轮改分句判定后才显形）。⇒ 半角/全角空格各补一条定长回顾。
    r'(?<!第)(?<!第 )(?<!第\u3000)\d+\s*'
    r'(?:%|％|ms|s\b|秒|分钟|小时|天|周|月|人|个|条|张|万|亿|MB|GB|px)|'
    r'(?<!第)(?<!第 )(?<!第\u3000)\d+\s*次(?!评审|会议|讨论)|'
    r'不超过|不低于|至少|最多|上限|下限|阈值|超过\s*\d|低于\s*\d|'
    # ⚠️ codex #7：`采用\s*[^\s什么哪]{2,}` 把「**待定方案**」也当成有效宾语 ⇒
    #   `answer_state("采用待定方案") == YES` —— 正好违反 129-131 行声称已排除的情况。
    #   ⇒ 宾语不许以延后语开头。
    r'由\S{2,}负责|'
    r'采用\s*(?!待定|待议|未定|不确定|以后|后续)[^\s什么哪]{2,}|'
    r'使用\s*(?!待定|待议|未定|不确定|以后|后续)[^\s什么哪]{2,}|限制在\s*[^\s]{2,}|'
    r'保证\s*[^\s]{2,}|承诺\s*[^\s]{2,}')


# ⭐ 封闭类虚词表 —— 剥掉它们之后「还剩不剩东西」是本门的实质判据。
#   ⚠️ 为什么枚举这一张表是合法的，而枚举「延后语」不合法：
#     **虚词是封闭类**（汉语的连词/助词/方位词就这么些，几十年不新增），
#     **延后语是开放类**（「以后再定」「回头捋捋」「等三季度」…可以无限造新说法）。
#     ⇒ 对封闭类做穷举是可收敛的；对开放类做穷举是打地鼠，四版都栽在这上面。
#   量程含**方位词**（后/前/上/下/中/内/外/里）：它们同属封闭类，且「…后再做决定」
#   剥完只剩一个「后」时，那个「后」不是答案 —— 实测差这一个字就漏判。
#   ⚠️ 2026-09-10：收窄 `再X` 通配后，「…后**再**做决定」剥完剩一个孤零零的「再」——
#     它是副词，同属封闭类，补进来（`再生` 不受影响：那一格什么都没被剥，
#     虚词剥离根本不触发）。
_FUNCTION_WORDS = '的了着过和与及或而并就才也都很更还只则等吧呢啊呀吗嘛把被在于后前上下中内外里再'

# 过程性措辞 —— 描述「怎么通往答案」，不是答案本身。
#   ⚠️ 它**不用来直接判红**（那正是 18cf0b5 制造误伤的原因：「需要登录才能查看」
#     里的「需要」和「需要进一步评估」里的「需要」一模一样）。
#     它只用来做「剥掉之后还剩不剩内容」的剥离，判据是**剩余为空**，不是词命中。
_PROCESS_WORDS = re.compile(
    r'需要|进一步|综合考虑|各方面|因素|讨论|评估|商榷|研究|沟通|对齐|确认|'
    r'最终|定下来|才能|会议|评审|这部分|内容|做决定|有待|后续|将来|届时|到时|'
    # ⚠️ codex #6：`看[^\s，。]{0,4}` 太贪 —— 它整词吃掉「**看板**」这个合法产品名词。
    #   ⇒ 只认真正表示「以后再看」的搭配，不再通配。
    # ⚠️ codex 二轮 #13：`再[^\s，。]{0,3}` 太贪 —— 它吃掉合法词「**再生**」。
    #   ⇒ 只认「再+决定类动词」这一族（封闭），不再通配。
    r'之后|下一步|然后|以后|再说|再定|再议|再确认|再评估|再讨论|再看|'
    r'等看|看情况|看数据|看反馈|看效果|'
    # ⚠️ 2026-09-10 补：「这块」与「这部分」同义（后者早在表里，前者漏了）；
    #   「等 3 个月」这类**时长指向未来**的说法也是过程而非答案。
    r'这块|等\s*\d+\s*个?\s*(?:月|周|天|年|季度|小时|分钟)|'
    r'根据[^\s，。]{0,6}决定|视[^\s，。]{0,4}而定')

# 原地转引 —— 「同上」这类把答案推给别处却没说是哪儿的写法。
#   ⚠️ 与「参见附录 A」「详见 PRD 第三章」有本质区别：后者**指名道姓**，
