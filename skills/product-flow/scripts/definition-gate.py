def is_defer(text):
    """兼容入口：只有**机器可判定的没答**才算 True。

    ⛔ UNJUDGED 一律不算 defer —— 这条是上一版误伤的直接修复：
      判不了不等于没答，把「判不了」当「没答」去判红，就是在惩罚正确产物。
    """
    return answer_state(text) == 'NO'


def nonempty(body):
    """一节算「填了」的判据。

    ⚠️ **表头不是内容。** 首版只剥了分隔行与占位符，于是一张
    「只剩表头的空表」（`| 不做什么 | 为什么 | …|` + `|---|---|`）
    因为表头文字够长而被判成「填了」——**空表格看起来像填了，其实是没想过**，
    这正是这条规则要抓的东西，却被它自己放过。
    修法：**有表格的节，必须至少有一行「数据行」**（分隔行之后、且不全是占位符的 `|` 行）。
    """
    if body is None: return False
    lines = body.split('\n')
    sep_idx = [i for i, l in enumerate(lines) if re.match(r'^\s*\|[\s\-:|]+\|\s*$', l)]
    if sep_idx:
        # 表格节：数一数分隔行之后有几行真数据
        data = 0
        for l in lines[sep_idx[0] + 1:]:
            if not l.strip().startswith('|'): continue
            if re.match(r'^\s*\|[\s\-:|]+\|\s*$', l): continue
            cells = PLACEHOLDER.sub('', l).strip().strip('|')
            # ⛔ 整行每一格都是延后语 ⇒ 这行不算「数据」（见 DEFER_ONLY 的理由）
            if all(is_defer(c) or not c.strip()
                   for c in l.strip().strip('|').split('|')):
                continue
            if len(re.sub(r'[|\s>#*\-—·]', '', cells)) >= 2: data += 1
        if data: return True
        # 表格是空的 —— 再看表格之外还有没有正文
        outside = '\n'.join(lines[:sep_idx[0] - 1])
    else:
        outside = body
    # 🚨 2026-09-10 第六轮（自证抓到）：这里**先 `PLACEHOLDER.sub` 再判 is_defer** ——
    #   而 PLACEHOLDER 本身就含「待定/待填/TODO」⇒ **延后词被剥掉之后，
    #   剩下的部分看着像个答案**：「待定，见 v2 的 5 条需求」剥成「，见 v2 的 5 条需求」，
    #   `5 条` 一个承诺信号就判过了。⭐ 与本轮修的 E5 是同一个形状：
    #     **判定顺序把证据先删掉了**，判据再怎么对也没用。
    #   ⇒ 先拿**原文**判一次；原文就是延后语的，剥不剥都不算填了。
    if is_defer(outside):
        return False
    t = PLACEHOLDER.sub('', outside)
    if is_defer(t):          # 正文只写了「以后再定」⇒ 没答（标题形态的绕过）
        return False
    t = re.sub(r'[|\s>#*\-—·]', '', t)
    return len(t) >= 8


