# 指路表达（封闭类）—— 剥完只剩它时，说明这一格把答案推给了别处。
_POINTER_VERB = re.compile(r'见|参见|详见|参考|另见|如上|如下|详情|出处')

_PLACEHOLDER_ONLY = re.compile(
    # ⚠️ 2026-09-10：从 DEFER_ANY 移过来的第②类词在这里落地 —— **整格匹配**，
    #   于是「暂无」独占一格＝没答，而「暂无默认值，由调用方必填」是答案。
    r'^(?:略|无|空|待[定补填议]?|暂无|暂缺|暂不|暂时|先不做|等数据|等上线|等评审|'
    r'TBD|TODO|N/?A|None|null|nil|\?+|x+|-+|—+|/+|\.+|。+)$', re.I)


def answer_state(text):
    """这一格/这一段有没有给出答案 —— 返回 'NO' / 'YES' / 'UNJUDGED' 三态。

    🚨🚨 2026-09-09 **第五轮独立复核（约 490 个变体）推翻了第四版**，两条致命指控
      我复现后都成立，且第二条是本门自己造成的回归：

      ① **「倒过来判」写在注释里，没写进决策路径。** 上一版 docstring 写着
         「不问像不像还没答，问有没有给出实质答案」，而实测 **14/14 的「没答」
         判定全部由 `len(_eff) < 8` 这条长度阈值做出**，白名单一次都没参与判定；
         而阈值上方三行还写着「⭐ 长度从来不是判据」。
         ⭐ 在一个母题是「声称≠实际」的仓里，本门自己是最典型的一例。

      ② **它开始惩罚正确产物。** 「需要登录才能查看」「对齐现有权限体系」
         「不服务 B 端。」被判「没答」，报错还写「只有表头/占位符」——
         **错误诊断，会把人送去找一个不存在的占位符**（本仓纪律：错误诊断比漏报贵）。
         与此同时「这一项非常重要，团队高度重视，会认真对待。」满绿。
         ⭐ **门在放过它该拦的，拦住它该放的。**

    ⭐⭐ 根因（这一版真正改掉的东西）：
      「需要登录才能查看」与「需要进一步评估」**在词汇上没有任何区别** ——
      区别在于句子指向的是一个**东西**还是一个**「以后再决定」的过程**。
      正则判不了这个差别，**再加多少词表都判不了**。
      ⇒ 那就不要再假装能判。本版**收窄声称**，只保留机器真能判定的部分：

        · 'NO'       机器可判定的「没答」：空 / 纯符号表情 / 纯占位记号 /
                     原地转引（同上、见上）/ 剥掉延后语与过程性措辞后**一无所剩**。
                     ⭐ 判据是**剩余为空**（阈值 0），不是「剩余不够长」（阈值 N）——
                       长度门槛在本函数上已经错过三次，这次是结构性去掉它。
        · 'YES'      有量化承诺或明确主体动作（COMMIT_SIGNAL）。
        · 'UNJUDGED' 其余散文。⛔ **一律不判红**（判红就是 ② 那种误伤），
                     由调用方在绿灯上**声明边界**：本门判不了这格是不是真答案。

      「这一项非常重要…」落在 UNJUDGED：本门如实说自己判不了，
      而不是假装判过 —— 这比一个会误伤合法答案的假判据诚实，也更有用。
    """
    # 🚨🚨 2026-09-10 **构造空间穷举**（核心内容 × 包裹 × 尾随标点 × 前缀，2940 例）
    #   一次扫出 **160 例失配**，全是同一族：`- 略` / `（略）。` / `**（略）。` ——
    #   归一化做了一半且**顺序固定**：剥包裹发生在剥尾随标点**之前**，
    #   于是「先包裹、后加句号」这种再普通不过的写法整族逃逸；
    #   列表记号 `- ` 与引用记号根本没剥。
    #   ⭐ 这 160 个组合**我一个都列不出来** —— 穷举替我列了。
